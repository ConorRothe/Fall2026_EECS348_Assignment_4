#include <cctype>    // I use this to check whether a character is whitespace.
#include <fstream>   // This lets the program open and read the puzzle files.
#include <iostream>  // This is for printing the puzzles and results.
#include <string>    // This is for storing filenames and error messages.

// Source: Based on Claude's SudokuSolver class, with improvements from ChatGPT.
// This class keeps track of a Sudoku board and handles solving it.
class SudokuSolver {
public:
    static const int SIZE = 9;   // A regular Sudoku board has 9 rows and columns.
    static const int BLOCK = 3;  // Each smaller block is 3 by 3.
    static const int EMPTY = 0;  // I use 0 inside the program for an empty spot.

    // This structure holds all 81 numbers in one Sudoku board.
    struct Grid {
        int cells[SIZE][SIZE];  // Each position stores a number or 0 if empty.
    };

    // The constructor gets everything ready before a puzzle is loaded.
    SudokuSolver() : solutionCount(0), puzzleLoaded(false) {
        clearGrid(original);  // Start the original board as empty.
        clearGrid(working);   // Start the board used for solving as empty.
        clearMasks();         // Make sure no numbers are marked as used yet.
    }

    // This method reads one puzzle and checks its format before using it.
    bool loadFromFile(const std::string& filename, std::string& error) {
        puzzleLoaded = false;  // A new puzzle has not been loaded successfully yet.
        solutionCount = 0;     // Reset the solution count for this file.
        error.clear();         // Remove any old error message.
        clearGrid(original);   // Clear the last puzzle's original board.
        clearGrid(working);    // Clear the board we will solve.
        clearMasks();          // Reset which numbers are marked as used.

        std::ifstream input(filename.c_str());  // Try to open the requested file.
        if (!input) {                           // Check if opening the file failed.
            error = "could not open the file";  // Give a reason for the failure.
            return false;                      // Stop because there is no input.
        }

        int cellCount = 0;  // Count the Sudoku cells we have read so far.
        char ch;            // Store one character from the file at a time.

        while (input.get(ch)) {  // Keep reading until the file ends.
            // I let the file have spaces or newlines between its numbers.
            if (std::isspace(static_cast<unsigned char>(ch))) {
                continue;  // Whitespace is not counted as a Sudoku cell.
            }

            if (cellCount >= SIZE * SIZE) {  // There should only be 81 cells.
                error = "the file contains more than 81 puzzle cells";
                return false;  // Reject a file that has extra cell characters.
            }

            int value = EMPTY;  // Assume this cell is blank unless it is a digit.
            if (ch >= '1' && ch <= '9') {  // Check if the character is 1 through 9.
                value = ch - '0';          // Turn the character into an integer.
            }
            else if (ch != '_') {  // An underscore is the only allowed blank symbol.
                error = std::string("invalid character '") + ch +
                        "' (use digits 1-9 or '_')";
                return false;  // Do not try to solve a badly formatted file.
            }

            // Division gives the row, and the remainder gives the column.
            original.cells[cellCount / SIZE][cellCount % SIZE] = value;
            ++cellCount;  // Move to the next position in the puzzle.
        }

        if (cellCount != SIZE * SIZE) {  // Make sure all 81 positions were provided.
            error = "the file contains fewer than 81 puzzle cells";
            return false;  // An incomplete board should not be solved.
        }
        if (input.bad()) {  // Check whether something went wrong while reading.
            error = "an error occurred while reading the file";
            return false;
        }

        working = original;   // Keep one copy to change while solving.
        puzzleLoaded = true;  // The input is ready to use.
        return true;          // Tell the manager that loading worked.
    }

    // Show the puzzle as it looked before any numbers were filled in.
    void printOriginal() const {
        printGrid(original);  // The original board never gets changed by solving.
    }

    // This starts the solver after checking the original puzzle's numbers.
    void solveAll() {
        if (!puzzleLoaded) {  // Do not solve a puzzle that was never loaded.
            std::cout << "No solution found\n";
            return;
        }

        working = original;   // Start over with the untouched puzzle.
        solutionCount = 0;    // Start counting solutions from zero.

        if (!initializeMasks()) {  // Check for repeated starting numbers.
            std::cout << "No solution found\n";
            return;  // The clues already break the Sudoku rules.
        }

        int emptyCount = 0;  // Count how many spaces still need numbers.
        for (int row = 0; row < SIZE; ++row) {       // Go through each row.
            for (int col = 0; col < SIZE; ++col) {   // Check every column.
                if (working.cells[row][col] == EMPTY) {
                    ++emptyCount;  // Add one for each blank space.
                }
            }
        }

        solveRecursive(emptyCount);  // Try to fill every blank using backtracking.
        if (solutionCount == 0) {     // Check if the search found nothing.
            std::cout << "No solution found\n";
        }
    }

private:
    // Nine 1-bits represent the possible Sudoku digits 1 through 9.
    static const int ALL_DIGITS = (1 << SIZE) - 1;

    Grid original;  // Save the starting puzzle so I can display it later.
    Grid working;   // Change this copy as the solver tries numbers.

    // These arrays track the used digits without searching every cell each time.
    int rowUsed[SIZE];    // Digits already used in each row.
    int colUsed[SIZE];    // Digits already used in each column.
    int blockUsed[SIZE];  // Digits already used in each 3x3 block.

    unsigned long long solutionCount;  // Count solutions instead of saving boards.
    bool puzzleLoaded;                 // Remember whether the file loaded correctly.

    // Set every position in a board back to an empty cell.
    static void clearGrid(Grid& grid) {
        for (int row = 0; row < SIZE; ++row) {      // Go across all rows.
            for (int col = 0; col < SIZE; ++col) {  // Visit each cell in the row.
                grid.cells[row][col] = EMPTY;      // Mark this spot as blank.
            }
        }
    }

    // Reset all of the used-number records before working on a puzzle.
    void clearMasks() {
        for (int i = 0; i < SIZE; ++i) {
            rowUsed[i] = 0;    // No digits have been used in this row yet.
            colUsed[i] = 0;    // No digits have been used in this column yet.
            blockUsed[i] = 0;  // No digits have been used in this block yet.
        }
    }

    // Figure out which of the nine smaller blocks a cell belongs to.
    static int blockIndex(int row, int col) {
        return (row / BLOCK) * BLOCK + col / BLOCK;
    }

    // Check the starting clues and record each number in the bitmasks.
    bool initializeMasks() {
        clearMasks();  // Make sure we are not using data from another search.
        for (int row = 0; row < SIZE; ++row) {
            for (int col = 0; col < SIZE; ++col) {
                int num = working.cells[row][col];  // Get the current clue.
                if (num == EMPTY) {  // Blank cells cannot cause a duplicate.
                    continue;
                }

                int bit = 1 << (num - 1);       // Give this number its own bit.
                int block = blockIndex(row, col);  // Find its smaller block.

                // If the bit is already turned on, this clue repeats a number.
                if ((rowUsed[row] & bit) ||
                    (colUsed[col] & bit) ||
                    (blockUsed[block] & bit)) {
                    return false;  // The starting puzzle is not valid.
                }

                rowUsed[row] |= bit;      // Mark the number as taken in this row.
                colUsed[col] |= bit;      // Mark it as taken in this column.
                blockUsed[block] |= bit;  // Mark it as taken in this block.
            }
        }
        return true;  // None of the clues conflict with each other.
    }

    // Find the possible digits for one empty space using the used-number masks.
    int candidatesFor(int row, int col) const {
        int blocked = rowUsed[row] |            // Numbers already in the row,
                      colUsed[col] |            // the column,
                      blockUsed[blockIndex(row, col)];  // or the 3x3 block.
        return ALL_DIGITS & ~blocked;  // Keep only the digits that are not used.
    }

    // Count how many possible digits are turned on in a mask.
    static int countBits(int mask) {
        int count = 0;  // Start with no possible digits counted.
        while (mask != 0) {  // Keep going until no bits are left.
            mask &= mask - 1;  // Remove one set bit each time through the loop.
            ++count;          // That bit represented one possible number.
        }
        return count;  // Tell the solver how many choices this cell has.
    }

    // Pick the empty cell with the fewest choices to limit unnecessary guesses.
    bool chooseMostRestrictedCell(int& bestRow, int& bestCol,
                                  int& bestMask) const {
        int lowestCount = SIZE + 1;  // Start higher than the maximum 9 choices.
        bestRow = -1;                 // -1 means no empty cell has been picked.
        bestCol = -1;
        bestMask = 0;                 // No possible digits have been selected yet.

        for (int row = 0; row < SIZE; ++row) {
            for (int col = 0; col < SIZE; ++col) {
                if (working.cells[row][col] != EMPTY) {
                    continue;  // Ignore spots that already have numbers.
                }

                int mask = candidatesFor(row, col);  // Find available digits.
                int count = countBits(mask);        // See how many choices exist.

                if (count < lowestCount) {  // This spot is more restricted.
                    lowestCount = count;    // Save the new smallest choice count.
                    bestRow = row;          // Remember where this spot is.
                    bestCol = col;
                    bestMask = mask;        // Save the digits we could place here.

                    if (count <= 1) {  // A zero is a dead end; one is a forced move.
                        return count == 1;  // Stop scanning because we cannot do better.
                    }
                }
            }
        }
        return bestRow != -1;  // True means an empty cell was found.
    }

    // This is the recursive part: try a number, go forward, then undo it.
    void solveRecursive(int remaining) {
        if (remaining == 0) {  // No blank spaces means a solution was found.
            ++solutionCount;  // Number this solution for the output.
            std::cout << "Solution " << solutionCount << ":\n";
            printGrid(working);  // Print the solution now instead of saving it.
            std::cout << '\n';    // Separate this solution from the next one.
            return;             // Go back and check for other possible solutions.
        }

        int row, col, candidates;  // Hold the cell and its available digits.
        if (!chooseMostRestrictedCell(row, col, candidates)) {
            return;  // No legal choice means this path cannot solve the puzzle.
        }

        for (int num = 1; num <= SIZE; ++num) {  // Try the numbers 1 through 9.
            int bit = 1 << (num - 1);  // Find this number's matching bit.
            if (!(candidates & bit)) {
                continue;  // Skip a number that breaks the Sudoku rules.
            }

            int block = blockIndex(row, col);  // Find the selected cell's block.
            working.cells[row][col] = num;    // Try placing this number.
            rowUsed[row] |= bit;              // Mark it used in the row.
            colUsed[col] |= bit;              // Mark it used in the column.
            blockUsed[block] |= bit;          // Mark it used in the block.

            solveRecursive(remaining - 1);  // Try to solve the rest of the puzzle.

            // If we return here, undo the move before trying the next number.
            working.cells[row][col] = EMPTY;  // Empty the cell again.
            rowUsed[row] &= ~bit;             // Make the digit available in the row.
            colUsed[col] &= ~bit;             // Make it available in the column.
            blockUsed[block] &= ~bit;         // Make it available in the block.
        }
    }

    // Print the grid with lines separating the smaller 3x3 blocks.
    static void printGrid(const Grid& grid) {
        for (int row = 0; row < SIZE; ++row) {  // Print one row at a time.
            if (row > 0 && row % BLOCK == 0) {  // Every third row needs a divider.
                std::cout << "------+-------+------\n";
            }

            for (int col = 0; col < SIZE; ++col) {
                if (col > 0 && col % BLOCK == 0) {
                    std::cout << "| ";  // Separate the 3-column blocks.
                }

                int value = grid.cells[row][col];  // Get the number to display.
                if (value == EMPTY) {
                    std::cout << '_';  // Show an underscore for a blank cell.
                }
                else {
                    std::cout << value;  // Otherwise print the actual number.
                }

                if (col < SIZE - 1) {
                    std::cout << ' ';  // Put a space between neighboring cells.
                }
            }
            std::cout << '\n';  // Go to the next row of the board.
        }
    }
};  // End of SudokuSolver.

// Source: Based on Claude's PuzzleManager class, with ChatGPT-assisted comments.
// This class handles the five files so SudokuSolver can focus on solving.
class PuzzleManager {
public:
    // Go through the five puzzle filenames in order.
    void runAll() const {
        for (int number = 1; number <= 5; ++number) {
            std::string filename =
                "puzzle" + std::to_string(number) + ".txt";  // Make puzzle1.txt, etc.
            processPuzzle(filename);  // Load and solve this specific file.
        }
    }

private:
    // Deal with one puzzle, then return to runAll for the next file.
    void processPuzzle(const std::string& filename) const {
        std::cout << "==============================\n";
        std::cout << "Puzzle file: " << filename << '\n';  // Show which file this is.
        std::cout << "==============================\n";

        SudokuSolver solver;  // Give each file its own solver and board.
        std::string error;    // Store a message if loading fails.

        if (!solver.loadFromFile(filename, error)) {  // Try reading the puzzle.
            std::cout << "Error: " << error
                      << " in " << filename << "\n\n";  // Tell the user what happened.
            return;  // Skip this file but still allow the next one to run.
        }

        std::cout << "Original puzzle:\n";
        solver.printOriginal();  // Show what the puzzle looked like at first.
        std::cout << "\nSolutions:\n";
        solver.solveAll();       // Search for and print every solution.
        std::cout << '\n';       // Put space between this puzzle and the next.
    }
};  // End of PuzzleManager.

// Source: Original program flow from Claude, with comments revised by ChatGPT.
int main() {
    PuzzleManager manager;  // Create the object that manages all five files.
    manager.runAll();       // Run the assignment's five Sudoku puzzles.
    return 0;              // Finish the program normally.
}
